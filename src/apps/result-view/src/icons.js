const NS = 'http://www.w3.org/2000/svg';

/** A lucide icon as an SVG element (decorative: aria-hidden, the text next to it carries meaning). */
export function icon(name, className = 'icon') {
  const svg = document.createElementNS(NS, 'svg');
  for (const [k, v] of Object.entries({ viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', 'stroke-width': '2', 'stroke-linecap': 'round', 'stroke-linejoin': 'round', 'aria-hidden': 'true', class: className })) svg.setAttribute(k, v);
  // static markup from the table above — never data
  svg.innerHTML = PATHS[name];
  return svg;
}
